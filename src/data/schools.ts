export const ONESIZE_OPTIONS = ['Junior (Age 4–10)', 'Intermediate (Age 11–14)', 'Senior (Age 15–18)'];

export function getDefaultSizeForSchool(sizeType: UniformItem['sizeType'], level: School['level']): string {
  const isSenior = level === 'Senior / High Schools';
  switch (sizeType) {
    case 'garment':
      return isSenior ? GARMENT_SIZES[7] : GARMENT_SIZES[3]; // Size 36 or Size 28
    case 'bottom':
      return isSenior ? BOTTOM_SIZES[5] : BOTTOM_SIZES[2]; // Waist 32 or Waist 26
    case 'shoe':
      return isSenior ? SHOE_SIZES[10] : SHOE_SIZES[4]; // Size 38 or Size 32
    case 'onesize':
      return isSenior ? ONESIZE_OPTIONS[2] : ONESIZE_OPTIONS[0];
  }
}

export function getSizeOptions(sizeType: UniformItem['sizeType']): string[] {
  switch (sizeType) {
    case 'garment':
      return GARMENT_SIZES;
    case 'bottom':
      return BOTTOM_SIZES;
    case 'shoe':
      return SHOE_SIZES;
    case 'onesize':
      return ONESIZE_OPTIONS;
  }
}

export function formatKes(amount: number): string {
  return `KES ${amount.toLocaleString('en-KE')}`;
}
