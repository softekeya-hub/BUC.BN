import { School, UniformItem } from '../types/uniform';

const makeAngleNotes = (
  itemName: string,
  category: UniformItem['category'],
  colorDesc: string
) => {
  switch (category) {
    case 'Top':
      return {
        front: `Front view: ${colorDesc} ${itemName} with crisp collar points, reinforced placket stitching, and chest pocket alignment.`,
        side: `Side profile: Neat sleeve cuff taper, underarm gusset freedom, and smooth side-seam hem.`,
        back: `Back view: Twin-pleat shoulder yoke for easy movement and tidy collar stand construction.`,
      };
    case 'Bottom':
      return {
        front: `Front view: ${colorDesc} ${itemName} showing tailored waistband, belt loops / crisp pleat fall, and deep side pockets.`,
        side: `Side profile: Knife-sharp trouser crease or uniform skirt pleat spacing down to knee/ankle hem.`,
        back: `Back view: Reinforced seat seam, tidy pocket welt / zipped placket, and generous hem allowance.`,
      };
    case 'Knitwear':
      return {
        front: `Front view: ${colorDesc} ${itemName} featuring a clean V-neck / button placket rib and optional crest placement.`,
        side: `Side profile: Ribbed cuff elasticity and seamless shoulder-to-sleeve knit join.`,
        back: `Back view: Even acrylic-wool blend knit gauge with structured waist ribbing that holds shape.`,
      };
    case 'Blazer':
      return {
        front: `Front view: ${colorDesc} ${itemName} with notched lapels, brass/matched buttons, and lower patch pockets.`,
        side: `Side profile: Tailored sleeve pitch, shoulder pad balance, and clean lapel roll.`,
        back: `Back view: Twin-panel tailored back seam and neat center/side vent for active school days.`,
      };
    case 'Tie':
      return {
        front: `Front view: ${colorDesc} ${itemName} woven stripe pattern with crisp interlining for a neat knot.`,
        side: `Side profile: Slim tapered blade profile that sits flat under sweater V-necks.`,
        back: `Back view: Keeper loop and stitched tipping for durability across terms.`,
      };
    case 'Socks':
      return {
        front: `Front view: ${colorDesc} ${itemName} cotton-rich ribbed knit with stay-up cuff.`,
        side: `Side profile: Cushioned heel and ankle rib compression that prevents slipping inside shoes.`,
        back: `Back view: Seamless toe and reinforced Achilles heel guard.`,
      };
    case 'Shoes':
      return {
        front: `Front view: ${colorDesc} ${itemName} polished full-grain leather toe box with sturdy eyelets/straps.`,
        side: `Side profile: Non-slip moulded rubber lug sole and arch-supportive school-day heel.`,
        back: `Back view: Padded ankle collar and rigid heel counter for long walks along Banana Hill.`,
      };
    case 'Games / PE':
      return {
        front: `Front view: ${colorDesc} ${itemName} breathable sportswear front panel with contrast piping.`,
        side: `Side profile: Athletic raglan sleeve/side stripe alignment and flexible stretch trim.`,
        back: `Back view: Moisture-wicking back panel built for Kiambu highland sports fields.`,
      };
  }
};

function item(
  id: string,
  name: string,
  category: UniformItem['category'],
  priceKes: number,
  sizeType: UniformItem['sizeType'],
  colorDesc: string,
  defaultInclude = true,
  note?: string
): UniformItem {
  return {
    id,
    name,
    category,
    priceKes,
    sizeType,
    defaultInclude,
    note,
    angleNotes: makeAngleNotes(name, category, colorDesc),
  };
}

